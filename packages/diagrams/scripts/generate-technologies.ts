/**
 * Generates `src/notations/technologies.ts`, the logo table, from the
 * simple-icons package. For each Technology in the list below, the table
 * holds its slug, its display name, and its logo's path data. It reads nothing
 * else, so it gives the same output every time it runs on the same version of
 * simple-icons, which `package.json` pins exactly: even a patch release may
 * change an icon's path.
 *
 * Simple Icons is under CC0, but some of its icons carry licenses of their
 * own, so the script takes only icons with none, or with CC0's.
 *
 * Usage: node packages/diagrams/scripts/generate-technologies.ts [output]
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { SimpleIcon } from "simple-icons";
import * as simpleIcons from "simple-icons";

/**
 * The Technologies that have a logo: the slug that Diagrams write, and the
 * slug of its icon in Simple Icons. To add a Technology, add its line here,
 * then run `pnpm generate:technologies`. A slug that isn't listed still
 * works, and is drawn as its name.
 */
const technologies: Record<string, string> = {
	// Databases and other stores
	clickhouse: "clickhouse",
	couchbase: "couchbase",
	elasticsearch: "elasticsearch",
	etcd: "etcd",
	influxdb: "influxdb",
	mariadb: "mariadb",
	minio: "minio",
	mongodb: "mongodb",
	mysql: "mysql",
	neo4j: "neo4j",
	opensearch: "opensearch",
	postgres: "postgresql",
	redis: "redis",
	scylladb: "scylladb",
	sqlite: "sqlite",
	// Message brokers
	"google-pubsub": "googlepubsub",
	mosquitto: "eclipsemosquitto",
	nats: "natsdotio",
	rabbitmq: "rabbitmq",
	// Languages
	c: "c",
	clojure: "clojure",
	cpp: "cplusplus",
	dart: "dart",
	elixir: "elixir",
	erlang: "erlang",
	fsharp: "fsharp",
	go: "go",
	haskell: "haskell",
	kotlin: "kotlin",
	lua: "lua",
	python: "python",
	scala: "scala",
	swift: "swift",
	typescript: "typescript",
	// Runtimes
	bun: "bun",
	docker: "docker",
	dotnet: "dotnet",
	kubernetes: "kubernetes",
	nodejs: "nodedotjs",
	webassembly: "webassembly",
	// Clouds
	"alibaba-cloud": "alibabacloud",
	cloudflare: "cloudflare",
	"cloudflare-workers": "cloudflareworkers",
	digitalocean: "digitalocean",
	"fly-io": "flydotio",
	"google-cloud": "googlecloud",
	hetzner: "hetzner",
	netlify: "netlify",
	ovh: "ovh",
	scaleway: "scaleway",
	vercel: "vercel",
	// Gateways and proxies
	envoy: "envoyproxy",
	haproxy: "haproxy",
	kong: "kong",
	nginx: "nginx",
	traefik: "traefikproxy",
	// Protocols
	graphql: "graphql",
};

const output =
	process.argv[2] ?? fileURLToPath(new URL("../src/notations/technologies.ts", import.meta.url));

// simple-icons has no `"type"` field, so TypeScript takes its types for
// CommonJS, and gives the namespace a `default` that the module doesn't have.
const icons = new Map(
	Object.values(simpleIcons)
		.filter((icon): icon is SimpleIcon => "slug" in icon)
		.map((icon) => [icon.slug, icon]),
);
const { version } = JSON.parse(
	readFileSync(new URL("package.json", import.meta.resolve("simple-icons")), "utf8"),
) as { version: string };

/** A Technology's slug, as the model takes it: lowercase words joined by hyphens. */
const slugPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
/** A key that JavaScript reads without quotes. */
const identifierPattern = /^[a-z_$][a-z0-9_$]*$/;

const entries = Object.keys(technologies)
	.sort()
	.map((slug) => {
		const iconSlug = technologies[slug] ?? "";
		const icon = icons.get(iconSlug);
		if (!slugPattern.test(slug)) {
			throw new Error(`\`${slug}\` isn't a slug: write lowercase words joined by hyphens.`);
		}
		if (icon === undefined) {
			throw new Error(`Simple Icons ${version} has no icon \`${iconSlug}\`, for \`${slug}\`.`);
		}
		if (icon.license !== undefined && icon.license.type !== "CC0-1.0") {
			throw new Error(
				`Simple Icons' \`${iconSlug}\` is under ${icon.license.type}, not CC0, so its logo can't be bundled. Leave \`${slug}\` out of the list: a Technology without a logo is drawn as its name.`,
			);
		}
		if (!icon.svg.includes('viewBox="0 0 24 24"')) {
			throw new Error(`Simple Icons' \`${iconSlug}\` isn't drawn in a square 24 units wide.`);
		}
		return [
			`\t${identifierPattern.test(slug) ? slug : JSON.stringify(slug)}: {`,
			`\t\tname: ${JSON.stringify(icon.title)},`,
			`\t\tpath: ${JSON.stringify(icon.path)},`,
			"\t},",
		].join("\n");
	});

const header = `/**
 * The logo table: each Technology that has a logo, by its slug, with its
 * display name and its logo's path data, drawn in a square 24 units wide.
 * Generated by \`pnpm generate:technologies\` from simple-icons ${version}, whose
 * icons are under CC0 1.0: don't edit it. To add a Technology, add a line to
 * the list in \`scripts/generate-technologies.ts\`.
 */
`;

writeFileSync(output, `${header}\nexport const technologies = {\n${entries.join("\n")}\n};\n`);
