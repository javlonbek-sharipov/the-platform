/**
 * Generates `src/core/font-metrics.ts` from the bundled Inter fonts, so that
 * the core can measure text without reading a font file. For each weight, it
 * writes the units per em, the average width, and the advance width of every
 * character the font has. It reads nothing else, so it gives the same output
 * every time it runs on the same fonts.
 *
 * Usage: node packages/diagrams/scripts/generate-font-metrics.ts [output]
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { bundledFontFiles } from "../src/fonts/bundled.ts";
import { readTrueType, type TrueTypeFont, view } from "../src/fonts/truetype.ts";

const output =
	process.argv[2] ?? fileURLToPath(new URL("../src/core/font-metrics.ts", import.meta.url));

const header = `/**
 * The bundled Inter fonts' metrics, which the core measures text with.
 * Generated by \`pnpm generate:font-metrics\` from the font files: don't edit it.
 *
 * Every width is in font units. \`averageWidth\` is the font's own average
 * character width, from its OS/2 table. In \`widths\`, each row covers 16
 * consecutive code points: its first field is the first code point, in hex,
 * and the others are their advance widths, or \`-\` for a character the font
 * lacks.
 */
`;

const weights = Object.entries(bundledFontFiles).map(([weight, file]) => {
	const font = readTrueType(new Uint8Array(readFileSync(file)));
	return [
		`\t${weight}: {`,
		`\t\tunitsPerEm: ${font.unitsPerEm},`,
		`\t\taverageWidth: ${view(tableOf(font, "OS/2")).getInt16(2)},`,
		"\t\twidths: [",
		...rowsOf(font).map((row) => `\t\t\t"${row}",`),
		"\t\t],",
		"\t},",
	].join("\n");
});

writeFileSync(output, `${header}\nexport const fontMetrics = {\n${weights.join("\n")}\n};\n`);

/** One row for each run of 16 code points that holds at least one of the font's characters. */
function rowsOf(font: TrueTypeFont): string[] {
	const starts = [...new Set([...font.characters.keys()].map((code) => code - (code % 16)))];
	return starts
		.sort((a, b) => a - b)
		.map((start) => {
			const fields = [start.toString(16).toUpperCase().padStart(4, "0")];
			for (let code = start; code < start + 16; code++) {
				const glyph = font.characters.get(code);
				fields.push(glyph === undefined ? "-" : String(font.advanceWidth(glyph)));
			}
			return fields.join(" ");
		});
}

function tableOf(font: TrueTypeFont, tag: string): Uint8Array {
	const table = font.tables.get(tag);
	if (table === undefined) {
		throw new Error(`The font has no \`${tag}\` table.`);
	}
	return table;
}
